/**
 * Native Arabic pages — the SEO-friendly replacement for the old
 * Google-Translate-widget approach. Each `ArPage` is a fully self-contained,
 * professionally written Arabic page served at `/ar/{slug}` (Arabic slug,
 * per the site's URL spec) and cross-linked back to its English original via
 * `enPath`, which drives hreflang, canonical alternates, and the language
 * switcher.
 *
 * This is Phase 1 of the Arabic rollout: the full routing/RTL/hreflang/schema
 * pipeline, proven end-to-end with a flagship page per template type (a
 * service pillar, an airport, a city, a route, a hotel transfer, a blog
 * post, plus About/Contact). Bulk-translating the remaining ~350 pages is a
 * scoped follow-on that reuses this exact same registry shape — just append
 * more `ArPage` objects; no template or routing changes are needed.
 */

export type ArPageType =
  | "about"
  | "contact"
  | "service"
  | "airport"
  | "city"
  | "route"
  | "hotel-transfer"
  | "blog";

export interface ArFaq {
  question: string;
  answer: string;
}

export interface ArSection {
  heading: string;
  paragraphs: string[];
}

export interface ArPage {
  /** URL segment after /ar/ — Arabic script, unique, matches the site's Arabic-slug spec. */
  slug: string;
  type: ArPageType;
  /** The canonical English path this page is the Arabic translation of (drives hreflang). */
  enPath: string;
  /** <title> / metaTitle (≤60 chars is the target, Arabic character count). */
  metaTitle: string;
  metaDescription: string;
  h1: string;
  intro: string;
  sections: ArSection[];
  faqs: ArFaq[];
  /** Arabic breadcrumb trail: {name, path}, path already prefixed with /ar. */
  breadcrumbs: { name: string; path: string }[];
  heroImage?: string;
  heroAlt?: string;
  /** Distance/duration chips, for route/airport/hotel-transfer pages. */
  distance?: string;
  duration?: string;
}

