/** Full /ar/{slug} path for an ArPage. */
export function arPath(page: ArPage): string {
  return `/ar/${page.slug}`;
}

/** Given an English path, return its Arabic counterpart's full path, if one exists. */
export function getArPathForEnPath(enPath: string): string | undefined {
  if (enPath === "/") return "/ar";
  const page = arPages.find((p) => p.enPath === enPath);
  return page ? arPath(page) : undefined;
}

/** Given an /ar/{slug} path, return the English counterpart's full path. */
export function getEnPathForArPath(arFullPath: string): string {
  if (arFullPath === "/ar" || arFullPath === "/ar/") return "/";
  const slug = arFullPath.replace(/^\/ar\/?/, "");
  const page = getArPage(decodeURIComponent(slug));
  return page?.enPath ?? "/";
}
